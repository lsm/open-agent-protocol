use oap_adapter::gotime::rfc3339_millis;

#[test]
fn rfc3339_reads_offsets_and_fractions_as_unix_milliseconds() {
    for (text, want) in [
        ("1970-01-01T00:00:00Z", 0),
        ("2026-10-06T10:00:00.5+02:00", 1_791_273_600_500),
        ("2026-10-06T08:00:00.123456789Z", 1_791_273_600_123),
        ("2026-10-06T08:00:00.1234567890Z", 1_791_273_600_123),
        ("2026-10-06T03:30:00-04:30", 1_791_273_600_000),
        ("2024-02-29T00:00:00Z", 1_709_164_800_000),
        ("1969-12-31T23:59:59Z", -1000),
        ("2026-10-06T08:00:00,5Z", 1_791_273_600_500),
        ("2026-10-06T08:00:00,5+01:00", 1_791_270_000_500),
        ("2026-10-06T08:00:00+24:00", 1_791_187_200_000),
        ("2026-10-06T08:00:00+02:60", 1_791_262_800_000),
        ("2026-10-06T08:00:00+24:60", 1_791_183_600_000),
        ("2026-10-06T08:00:00-24:00", 1_791_360_000_000),
        ("2026-10-06T8:00:00Z", 1_791_273_600_000),
    ] {
        assert_eq!(rfc3339_millis(text), want, "{text}");
    }
}

#[test]
fn anything_go_s_rfc3339_layout_refuses_reads_as_zero() {
    for text in [
        "",
        "2026-10-06",
        "2026-10-06 08:00:00Z",
        "2026-10-06t08:00:00Z",
        "2026-10-06T08:00:00z",
        "2026-1-06T08:00:00Z",
        "2026-02-30T08:00:00Z",
        "2023-02-29T00:00:00Z",
        "2026-10-06T24:00:00Z",
        "2026-10-06T08:00:00.Z",
        "2026-10-06T08:00:00+0200",
        "2026-10-06T08:00:00+25:00",
        "2026-10-06T08:00:00+02:61",
        "2026-10-06T08:00:00+2:00",
        "2026-10-06T08:00:00,Z",
        "2026-10-06T08:00:00.1,2Z",
        "2026-10-06T008:00:00Z",
        "2026-10-06T08:0:00Z",
    ] {
        assert_eq!(rfc3339_millis(text), 0, "{text}");
    }
}
